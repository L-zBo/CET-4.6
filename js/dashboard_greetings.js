  // 时段+图标映射（与 dashboard.js 原逻辑保持一致）
  function bucketByHour(h) {
    if (h < 6)  return { key: 'night1',    icon: '🌙' };
    if (h < 9)  return { key: 'morning',   icon: '🌅' };
    if (h < 12) return { key: 'forenoon',  icon: '☀️' };
    if (h < 14) return { key: 'noon',      icon: '🌞' };
    if (h < 18) return { key: 'afternoon', icon: '🌤️' };
    if (h < 21) return { key: 'dusk',      icon: '🌆' };
    return { key: 'night2', icon: '🌙' };
  }

  // 把 weather_code 归一化成 6 类（与 weather.js getWeatherType 对齐）
  function bucketByWeather(code) {
    if (code == null) return 'cloudy';
    if (code === 0) return 'sunny';
    if (code <= 3)  return 'cloudy';
    if (code <= 49) return 'foggy';
    if ((code >= 51 && code <= 69) || (code >= 80 && code <= 82)) return 'rainy';
    if ((code >= 71 && code <= 79) || (code >= 83 && code <= 86)) return 'snowy';
    if (code >= 95) return 'stormy';
    return 'cloudy';
  }

  // 主入口：根据小时 + 天气代码挑一句问候
  // weatherCode 缺省时退化为只看时段（用 cloudy 中性档兜底）
  function pickGreeting(hour, weatherCode) {
    const { key, icon } = bucketByHour(hour);
    const wtype = bucketByWeather(weatherCode);
    const bucket = (G[key] && G[key][wtype]) || (G[key] && G[key].cloudy) || [];
    const text = bucket.length ? bucket[Math.floor(Math.random() * bucket.length)] : '继续加油';
    return { text, icon };
  }

  C.pickGreeting = pickGreeting;
